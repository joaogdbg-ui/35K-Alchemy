import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {DATA} from '../client/src/legacy-data.js';
import {PACK} from '../client/src/creative-pack.js';
import {buildCatalog,normalizeCatalogName} from '../client/src/catalog-integrity.js';
import {ORGANIC_V71} from '../client/src/organic-pack-v71.js';
import {ORGANIC_V72} from '../client/src/organic-pack-v72.js';
import {ORGANIC_V73} from '../client/src/organic-pack-v73.js';
import {ORGANIC_V74} from '../client/src/organic-pack-v74.js';
import {ORGANIC_V75} from '../client/src/organic-pack-v75.js';
import {ORGANIC_V76} from '../client/src/organic-pack-v76.js';
import {ORGANIC_V77} from '../client/src/organic-pack-v77.js';
import {ORGANIC_ART_V77} from '../client/src/organic-art-v77.js';
const check=(ok,message)=>{if(!ok)throw Error('V77: '+message);};
const m=JSON.parse(readFileSync('shared/v77-approved.json','utf8'));
check(m.version===77&&m.cohort_count===50&&m.new_items.length===50,'manifest size');
check(m.expansion_progress===100&&m.remaining_to_goal===100&&m.expansion_goal===200,'progress accuracy');
check(ORGANIC_V77.items.length===50&&ORGANIC_V77.recipes.length===50&&Object.keys(ORGANIC_ART_V77).length===50,'cohort sizes');
const groups=['gaming-v22','gaming-v23','gaming-v24','gaming-v26','gaming-v27','gaming-v30','organic-v32','organic-v34','organic-v37','organic-v38','organic-v40','organic-v41','organic-v42','organic-v43','organic-v44','organic-v45','organic-v46','organic-v47','organic-v50','organic-v52','organic-v53','organic-v55','organic-v56','organic-v57','organic-v58','organic-v59','organic-v61','organic-v62','organic-v63','organic-v65','organic-v66','organic-v67','organic-v68'];
const packs=[PACK];
for(const v of groups){const mod=await import('../client/src/'+v.replace('gaming','gaming-pack').replace('organic','organic-pack')+'.js');packs.push(Object.values(mod)[0]);}
const base=[...packs,ORGANIC_V71,ORGANIC_V72,ORGANIC_V73,ORGANIC_V74,ORGANIC_V75,ORGANIC_V76];
const prior=buildCatalog(DATA,base),now=buildCatalog(DATA,[...base,ORGANIC_V77]);
check(prior.items.length===5422&&prior.recipes.size===13759,'V76 baseline mutated');
check(now.items.length===5472&&now.recipes.size===13809,'V77 count mismatch');
for(const [pair,out] of prior.recipes)check(now.recipes.get(pair)===out,'old recipe overridden '+pair);
const knownNames=new Set(prior.items.map(x=>normalizeCatalogName(x.name)));
const existingArt=new Set(JSON.parse(readFileSync('shared/v76-approved.json','utf8')).new_items.map(x=>createHash('sha256').update(readFileSync(x.path,'utf8')).digest('hex')));
const accepted=new Set(['arcade','accessory','technology','culture','gamecraft','board','fantasy','music','science']);
const manifest=new Map(m.new_items.map(x=>[x.id,x]));
check(manifest.size===50,'duplicate manifest ids');
const ids=new Set(),names=new Set(),pairs=new Set(),images=new Set();
for(const it of ORGANIC_V77.items){
 const entry=manifest.get(it.id);check(entry?.name===it.name&&entry.art_mode==='bespoke-subject','unapproved element '+it.name);
 const norm=normalizeCatalogName(it.name);check(!knownNames.has(norm)&&!names.has(norm),'duplicate element '+it.name);names.add(norm);
 check(!ids.has(it.id),'duplicate element ID '+it.id);ids.add(it.id);
 check(accepted.has(it.category),'unsupported category '+it.name);
 check(it.summary.length>=40&&it.summary.length<180,'summary quality '+it.name);
 check(!/\b(?:nintendo|playstation|xbox|sega|pokemon|mario|sonic|zelda|kirby)\b/i.test(it.name+' '+it.summary),'non-generic media name '+it.name);
 const recipe=ORGANIC_V77.recipes.find(r=>r[2]===it.id);
 check(recipe?.[0]===entry.ingredients[0]&&recipe?.[1]===entry.ingredients[1],'recipe manifest mismatch '+it.name);
 const position=m.new_items.findIndex(x=>x.id===it.id);
 check(recipe.slice(0,2).every(id=>prior.items.some(x=>x.id===id)||m.new_items.findIndex(x=>x.id===id)>=0&&m.new_items.findIndex(x=>x.id===id)<position),'recipe input not already reachable '+it.name);
 const pair=recipe.slice(0,2).sort().join('|');
 check(!prior.recipes.has(pair)&&!pairs.has(pair),'duplicate/contradictory recipe '+it.name+' = '+pair);
 pairs.add(pair);check(now.recipes.get(pair)===it.id,'recipe not deterministic '+it.name);
 const svg=readFileSync(entry.path,'utf8'),hash=createHash('sha256').update(svg).digest('hex');
 check(svg.startsWith('<svg')&&svg.includes('viewBox="0 0 100 100"')&&svg.length>=410,'under-drawn SVG '+it.name);
 check(!/<(?:script|image|text|use|foreignObject|animate)\b|\s(?:href|onload|onclick)=/i.test(svg),'unsafe linked artwork '+it.name);
 check(!existingArt.has(hash)&&!images.has(hash),'duplicate V76/V77 SVG '+it.name);
 check(ORGANIC_ART_V77[it.name.toLowerCase()]===svg,'runtime art mismatch '+it.name);images.add(hash);
}
const app=readFileSync('client/src/app.js','utf8'),builder=readFileSync('tools/build-standalone.py','utf8');
check(app.includes('ORGANIC_V75,ORGANIC_V76,ORGANIC_V77,ORGANIC_V78,ORGANIC_V79]'),'pack missing from Classic');
check(app.includes('const newArt=ORGANIC_ART_V79[itemName]||ORGANIC_ART_V78[itemName]||ORGANIC_ART_V77[itemName]||ORGANIC_ART_V76'),'new art not preferred');
check(builder.includes('window.__gameverseOrganic77')&&builder.includes('window.__gameverseOrganicArt77'),'offline pack/art missing');
check(builder.includes('35K_Alchemy_V77_Offline.html'),'offline artifact wrong');
check(app.includes('const anchorId=this.ids[previousIndex]'),'inventory scroll regression');
if(!process.argv.includes('--quiet'))console.log('V77 PASS: +50 drawings; 5,472 elements, 13,809 unordered recipes, 100/200 delivered.');
