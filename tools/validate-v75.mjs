import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {DATA} from '../client/src/legacy-data.js';
import {PACK} from '../client/src/creative-pack.js';
import {buildCatalog,normalizeCatalogName} from '../client/src/catalog-integrity.js';
import {ORGANIC_V71} from '../client/src/organic-pack-v71.js';
import {ORGANIC_V72} from '../client/src/organic-pack-v72.js';
import {ORGANIC_V73} from '../client/src/organic-pack-v73.js';
import {ORGANIC_V74} from '../client/src/organic-pack-v74.js';
import {ORGANIC_V75} from '../client/src/organic-pack-v75.js';
import {ORGANIC_ART_V75} from '../client/src/organic-art-v75.js';
const check=(ok,msg)=>{if(!ok)throw Error('V75: '+msg);};
const manifest=JSON.parse(readFileSync('shared/v75-approved.json','utf8'));
check(manifest.version===75 && manifest.cohort_count===68 && manifest.new_items.length===68,'manifest count');
check(manifest.expansion_complete===200 && manifest.remaining_to_200===0,'expansion balance');
check(ORGANIC_V75.items.length===68 && ORGANIC_V75.recipes.length===68,'item/recipe count');
check(Object.keys(ORGANIC_ART_V75).length===68,'art source count or duplicate artwork key');
const modes=['gaming-v22','gaming-v23','gaming-v24','gaming-v26','gaming-v27','gaming-v30','organic-v32','organic-v34','organic-v37','organic-v38','organic-v40','organic-v41','organic-v42','organic-v43','organic-v44','organic-v45','organic-v46','organic-v47','organic-v50','organic-v52','organic-v53','organic-v55','organic-v56','organic-v57','organic-v58','organic-v59','organic-v61','organic-v62','organic-v63','organic-v65','organic-v66','organic-v67','organic-v68'];
const packs=[PACK];
for(const n of modes){const f=n.replace('gaming','gaming-pack').replace('organic','organic-pack');const mod=await import('../client/src/'+f+'.js');packs.push(Object.values(mod)[0]);}
const before=buildCatalog(DATA,[...packs,ORGANIC_V71,ORGANIC_V72,ORGANIC_V73,ORGANIC_V74]);
const after=buildCatalog(DATA,[...packs,ORGANIC_V71,ORGANIC_V72,ORGANIC_V73,ORGANIC_V74,ORGANIC_V75]);
check(before.items.length===5304 && before.recipes.size===13641,'V74 baseline unexpectedly changed');
check(after.items.length===5372 && after.recipes.size===13709,'V75 catalog counts');
for(const [key,result] of before.recipes)check(after.recipes.get(key)===result,'prior recipe output changed '+key);
const oldNames=new Set(before.items.map(x=>normalizeCatalogName(x.name)));
const approved=new Map(manifest.new_items.map(i=>[i.id,i]));
check(approved.size===68,'approved ID duplicates');
const hashes=new Set(),pairs=new Set(),names=new Set();
const validCategories=new Set(['game','genre','gamecraft','console','portable','computer','technology','brand','accessory','arcade','board','culture','fantasy','nature','material','science','object','concept','music']);
const previousArt=JSON.parse(readFileSync('shared/v74-approved.json','utf8'));
const previousHashes=new Set(previousArt.new_items.map(i=>createHash('sha256').update(readFileSync(i.path,'utf8')).digest('hex')));
for(const item of ORGANIC_V75.items) {
  const norm=normalizeCatalogName(item.name);
  check(!oldNames.has(norm)&&!names.has(norm),'duplicate concept '+item.name);
  names.add(norm);
  check(validCategories.has(item.category),'unmapped family category '+item.name);
  check(typeof item.summary==='string' && item.summary.length>=40 && !/(legacy|organic)\d*:[\w-]+/.test(item.summary),'inadequate description '+item.name);
  const rec=approved.get(item.id);
  check(rec?.name===item.name && rec.art_mode==='bespoke-subject','missing approved subject '+item.name);
  const recipe=ORGANIC_V75.recipes.find(x=>x[2]===item.id);
  check(recipe && recipe[0]===rec.ingredients[0] && recipe[1]===rec.ingredients[1],'recipe/manifest mismatch '+item.name);
  check(before.items.some(x=>x.id===recipe[0])&&before.items.some(x=>x.id===recipe[1]),'ingredient not discovered in previous versions '+item.name);
  const pair=[recipe[0],recipe[1]].sort().join('|');
  check(!before.recipes.has(pair)&&!pairs.has(pair),'existing or duplicate unordered recipe '+item.name);
  pairs.add(pair);
  check(after.recipes.get(pair)===item.id,'recipe outcome drift '+item.name);
  const svg=readFileSync(rec.path,'utf8');
  const hash=createHash('sha256').update(svg).digest('hex');
  check(!hashes.has(hash)&&!previousHashes.has(hash),'reused visual asset '+item.name);
  hashes.add(hash);
  check(ORGANIC_ART_V75[item.name.toLowerCase()]===svg,'in-game artwork is not the approved file '+item.name);
  check(svg.startsWith('<svg')&&svg.includes('viewBox="0 0 100 100"')&&svg.length>=350,'invalid or overly sparse artwork '+item.name);
  check(!/<script|<image\b|<text\b|<foreignObject|onload\s*=|href\s*=|<animate/i.test(svg),'unsafe/unsuitable SVG '+item.name);
}
const app=readFileSync('client/src/app.js','utf8');
const builder=readFileSync('tools/build-standalone.py','utf8');
check(app.includes('ORGANIC_V73,ORGANIC_V74,ORGANIC_V75,ORGANIC_V76,ORGANIC_V77,ORGANIC_V78,ORGANIC_V79,ORGANIC_V80,ORGANIC_V81,ORGANIC_V82,ORGANIC_V83]'),'V75 missing from playable catalog');
check(app.includes('ORGANIC_ART_V76[itemName]||ORGANIC_ART_V75[itemName]||ORGANIC_ART_V74[itemName]'),'V75 bespoke icon not prioritized');
check(builder.includes('window.__gameverseOrganicArt75')&&builder.includes('window.__gameverseOrganic75')&&builder.includes('35K_Alchemy_V76_Offline.html'),'V75 standalone/Android packaging missing');
check(app.includes('const anchorId=this.ids[previousIndex]'),'inventory scroll fix regressed');
check(readFileSync('client/src/styles.css','utf8').includes('.craft-row{transform:translateY(9px)}'),'combiner spacing regressed');
if(!process.argv.includes('--quiet'))console.log('V75 PASS: +68 individually authored SVGs, 5,372 elements, 13,709 fixed recipes, 200/200 expansion complete.');
