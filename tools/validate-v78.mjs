import {ORGANIC_V78} from '../client/src/organic-pack-v78.js';
import {ORGANIC_ART_V78} from '../client/src/organic-art-v78.js';
const check=(condition,message)=>{if(!condition)throw Error('V78: '+message);};
const m=JSON.parse(readFileSync('shared/v78-approved.json','utf8'));
check(m.version===78&&m.cohort_count===50&&m.new_items.length===50,'manifest size');
check(m.expansion_progress===150&&m.remaining_to_goal===50&&m.expansion_goal===200,'progress accuracy');
check(ORGANIC_V78.items.length===50&&ORGANIC_V78.recipes.length===50&&Object.keys(ORGANIC_ART_V78).length===50,'cohort sizes');
const groups=['gaming-v22','gaming-v23','gaming-v24','gaming-v26','gaming-v27','gaming-v30','organic-v32','organic-v34','organic-v37','organic-v38','organic-v40','organic-v41','organic-v42','organic-v43','organic-v44','organic-v45','organic-v46','organic-v47','organic-v50','organic-v52','organic-v53','organic-v55','organic-v56','organic-v57','organic-v58','organic-v59','organic-v61','organic-v62','organic-v63','organic-v65','organic-v66','organic-v67','organic-v68'];
const packs=[PACK];
for(const v of groups){const mod=await import('../client/src/'+v.replace('gaming','gaming-pack').replace('organic','organic-pack')+'.js');packs.push(Object.values(mod)[0]);}
const previous=[...packs,ORGANIC_V71,ORGANIC_V72,ORGANIC_V73,ORGANIC_V74,ORGANIC_V75,ORGANIC_V76,ORGANIC_V77];
const prior=buildCatalog(DATA,previous),next=buildCatalog(DATA,[...previous,ORGANIC_V78]);
check(prior.items.length===5472&&prior.recipes.size===13809,'V77 baseline changed');
check(next.items.length===5522&&next.recipes.size===13859,'V78 catalog totals');
for(const [pair,out] of prior.recipes)check(next.recipes.get(pair)===out,'historic pair outcome changed '+pair);
const knownNames=new Set(prior.items.map(x=>normalizeCatalogName(x.name)));
const prevArt=new Set(JSON.parse(readFileSync('shared/v77-approved.json','utf8')).new_items.map(x=>createHash('sha256').update(readFileSync(x.path,'utf8')).digest('hex')));
const approved=new Map(m.new_items.map(x=>[x.id,x]));
check(approved.size===50,'duplicate manifest IDs');
const accepted=new Set(['arcade','accessory','technology','culture','gamecraft','board','fantasy','music','science','nature']);
const ids=new Set(),names=new Set(),pairs=new Set(),images=new Set();
for(const it of ORGANIC_V78.items){
 const entry=approved.get(it.id);check(entry?.name===it.name&&entry.art_mode==='bespoke-subject','unapproved item '+it.name);
 const norm=normalizeCatalogName(it.name);check(!knownNames.has(norm)&&!names.has(norm),'duplicate name '+it.name);names.add(norm);
 check(!ids.has(it.id),'duplicate id '+it.id);ids.add(it.id);
 check(accepted.has(it.category),'unsupported category '+it.name);
 check(it.summary.length>=40&&it.summary.length<=180,'description length '+it.name);
 check(!/\b(?:nintendo|playstation|xbox|sega|pokemon|mario|sonic|zelda|kirby)\b/i.test(it.name+' '+it.summary),'named protected media '+it.name);
 const r=ORGANIC_V78.recipes.find(x=>x[2]===it.id);
 check(r?.[0]===entry.ingredients[0]&&r?.[1]===entry.ingredients[1],'recipe manifest mismatch '+it.name);
 check(r.slice(0,2).every(id=>prior.items.some(x=>x.id===id)),'unknown/unreachable previous ingredient '+it.name);
 const pair=r.slice(0,2).sort().join('|');
 check(!prior.recipes.has(pair)&&!pairs.has(pair),'duplicate/contradictory recipe '+it.name+' '+pair);pairs.add(pair);
 check(next.recipes.get(pair)===it.id,'non-deterministic result '+it.name);
 const svg=readFileSync(entry.path,'utf8'),hash=createHash('sha256').update(svg).digest('hex');
 check(svg.startsWith('<svg')&&svg.includes('viewBox="0 0 100 100"')&&svg.length>=410,'invalid SVG '+it.name);
 check(!/<(?:script|image|text|foreignObject|animate|use)\b|\s(?:href|onclick|onload)\s*=/i.test(svg),'external or unsafe vector '+it.name);
 check(!prevArt.has(hash)&&!images.has(hash),'duplicate V77/V78 SVG '+it.name);
 check(ORGANIC_ART_V78[it.name.toLowerCase()]===svg,'source/runtime SVG mismatch '+it.name);images.add(hash);
}
const app=readFileSync('client/src/app.js','utf8'),builder=readFileSync('tools/build-standalone.py','utf8');
check(app.includes('ORGANIC_V76,ORGANIC_V77,ORGANIC_V78,ORGANIC_V79,ORGANIC_V80,ORGANIC_V81,ORGANIC_V82,ORGANIC_V83]'),'new pack not in Classic');
check(app.includes('ORGANIC_ART_V80[itemName]||ORGANIC_ART_V79[itemName]||ORGANIC_ART_V78[itemName]||ORGANIC_ART_V77'),'new art not highest priority');
check(builder.includes('window.__gameverseOrganic78')&&builder.includes('window.__gameverseOrganicArt78'),'offline bundler lacks V78');
check(builder.includes('35K_Alchemy_V78_Offline.html'),'offline artifact not V78');
check(app.includes('const anchorId=this.ids[previousIndex]'),'inventory scroll regression');
if(!process.argv.includes('--quiet'))console.log('V78 PASS: +50 unique subjects and recipes; 5,522 items / 13,859 recipes; 150/200.');
