import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {DATA} from '../client/src/legacy-data.js';
import {PACK} from '../client/src/creative-pack.js';
import {buildCatalog,normalizeCatalogName} from '../client/src/catalog-integrity.js';
import {ORGANIC_V71} from '../client/src/organic-pack-v71.js';
import {ORGANIC_V72} from '../client/src/organic-pack-v72.js';
import {ORGANIC_V73} from '../client/src/organic-pack-v73.js';
import {ORGANIC_V74} from '../client/src/organic-pack-v74.js';
import {ORGANIC_V75} from '../client/src/organic-pack-v75.js';
import {ORGANIC_V76} from '../client/src/organic-pack-v76.js';
import {ORGANIC_ART_V76} from '../client/src/organic-art-v76.js';
const check=(condition,message)=>{if(!condition)throw Error('V76: '+message);};
const manifest=JSON.parse(readFileSync('shared/v76-approved.json','utf8'));
check(manifest.version===76&&manifest.cohort_count===50&&manifest.new_items.length===50,'manifest scope');
check(manifest.expansion_progress===50&&manifest.remaining_to_goal===150,'batch progress');
check(ORGANIC_V76.items.length===50&&ORGANIC_V76.recipes.length===50,'pack counts');
check(Object.keys(ORGANIC_ART_V76).length===50,'art key count');
const modes=['gaming-v22','gaming-v23','gaming-v24','gaming-v26','gaming-v27','gaming-v30','organic-v32','organic-v34','organic-v37','organic-v38','organic-v40','organic-v41','organic-v42','organic-v43','organic-v44','organic-v45','organic-v46','organic-v47','organic-v50','organic-v52','organic-v53','organic-v55','organic-v56','organic-v57','organic-v58','organic-v59','organic-v61','organic-v62','organic-v63','organic-v65','organic-v66','organic-v67','organic-v68'];
const packs=[PACK];
for(const name of modes){const path=name.replace('gaming','gaming-pack').replace('organic','organic-pack');const mod=await import('../client/src/'+path+'.js');packs.push(Object.values(mod)[0]);}
const prior=buildCatalog(DATA,[...packs,ORGANIC_V71,ORGANIC_V72,ORGANIC_V73,ORGANIC_V74,ORGANIC_V75]);
const current=buildCatalog(DATA,[...packs,ORGANIC_V71,ORGANIC_V72,ORGANIC_V73,ORGANIC_V74,ORGANIC_V75,ORGANIC_V76]);
check(prior.items.length===5372&&prior.recipes.size===13709,'V75 baseline unexpectedly changed');
check(current.items.length===5422&&current.recipes.size===13759,'V76 total count');
for(const [key,out] of prior.recipes)check(current.recipes.get(key)===out,'historical recipe outcome changed '+key);
const oldNames=new Set(prior.items.map(i=>normalizeCatalogName(i.name)));
const approved=new Map(manifest.new_items.map(i=>[i.id,i]));
check(approved.size===50,'duplicate approved ID');
const newNames=new Set(),newPairs=new Set(),hashes=new Set();
const allowedCats=new Set(['arcade','accessory','technology','culture','gamecraft','board','fantasy','music','console','portable']);
const previous=JSON.parse(readFileSync('shared/v75-approved.json','utf8'));
const lastHashes=new Set(previous.new_items.map(i=>createHash('sha256').update(readFileSync(i.path,'utf8')).digest('hex')));
for(const item of ORGANIC_V76.items){
  const normalized=normalizeCatalogName(item.name);
  check(!oldNames.has(normalized)&&!newNames.has(normalized),'duplicate concept '+item.name);
  newNames.add(normalized);
  check(allowedCats.has(item.category),'unknown family '+item.name);
  check(typeof item.summary==='string'&&item.summary.length>=40&&!/\blegacy:\d+|\borganic\d+:/i.test(item.summary),'description quality '+item.name);
  const entry=approved.get(item.id);
  check(entry?.name===item.name&&entry.art_mode==='bespoke-subject','missing approved record '+item.name);
  const rec=ORGANIC_V76.recipes.find(r=>r[2]===item.id);
  check(rec&&rec[0]===entry.ingredients[0]&&rec[1]===entry.ingredients[1],'recipe/manifest mismatch '+item.name);
  check(prior.items.some(i=>i.id===rec[0])&&prior.items.some(i=>i.id===rec[1]),'unknown ingredient '+item.name);
  const key=[rec[0],rec[1]].sort().join('|');
  check(!prior.recipes.has(key)&&!newPairs.has(key),'recipe collision '+item.name+' '+key);
  newPairs.add(key);
  check(current.recipes.get(key)===item.id,'non-deterministic recipe '+item.name);
  const svg=readFileSync(entry.path,'utf8');
  const hash=createHash('sha256').update(svg).digest('hex');
  check(!hashes.has(hash)&&!lastHashes.has(hash),'duplicate artwork '+item.name);
  hashes.add(hash);
  check(ORGANIC_ART_V76[item.name.toLowerCase()]===svg,'art source/runtime mismatch '+item.name);
  check(svg.startsWith('<svg')&&svg.includes('viewBox="0 0 100 100"')&&svg.length>=410,'invalid or generic sparse vector art '+item.name);
  check(!/<script|<image\b|<text\b|<foreignObject|onload\s*=|href\s*=|<animate/i.test(svg),'external/unsafe SVG '+item.name);
}
const app=readFileSync('client/src/app.js','utf8'),builder=readFileSync('tools/build-standalone.py','utf8');
check(app.includes('ORGANIC_V74,ORGANIC_V75,ORGANIC_V76,ORGANIC_V77,ORGANIC_V78,ORGANIC_V79,ORGANIC_V80,ORGANIC_V81,ORGANIC_V82]'),'V76 pack not in Classic');
check(app.includes('ORGANIC_ART_V76[itemName]||ORGANIC_ART_V75[itemName]'),'V76 artwork priority');
check(builder.includes('window.__gameverseOrganic76')&&builder.includes('window.__gameverseOrganicArt76'),'standalone data missing');
check(builder.includes('35K_Alchemy_V76_Offline.html'),'standalone version incorrect');
check(app.includes('const anchorId=this.ids[previousIndex]'),'scroll anchor regression');
check(readFileSync('client/src/styles.css','utf8').includes('.craft-row{transform:translateY(9px)}'),'upper combiner breathing room changed');
if(!process.argv.includes('--quiet'))console.log('V76 PASS: +50 individually composed SVG drawings, 5,422 elements, 13,759 recipes; 150 remaining for next 200.');
