#!/usr/bin/env python3
"""V208: real dark theme. Every component painted with hard-coded light colours is repainted dark in
html[data-theme="dark"]: backgrounds keep their hue at low lightness, light borders and 3-D drop shadows
darken, and dark text inside those components turns light. Regenerates the block between the DARK-SKIN
markers at the end of styles.css — run it after adding CSS with light backgrounds (a test checks)."""
import re,colorsys
P='client/src/styles.css';s=open(P).read()
A='/* DARK-SKIN:start (generated by tools/gen-dark-skin.py) */';B='/* DARK-SKIN:end */'
if A in s:s=s[:s.index(A)].rstrip()+'\n'
src=re.sub(r'/\*.*?\*/','',s,flags=re.S)
HEX=r'#[0-9a-fA-F]{3,8}\b'
def rgb(h):
    h=h.lstrip('#');h=''.join(c*2 for c in h[:3]) if len(h) in (3,4) else h[:6]
    return [int(h[i:i+2],16)/255 for i in (0,2,4)]
def lum(h):r,g,b=rgb(h);return .2126*r+.7152*g+.0722*b
def hx(r,g,b):return '#%02X%02X%02X'%tuple(round(max(0,min(1,v))*255) for v in (r,g,b))
def remap(h,L,smax=.5,sk=.55):
    r,g,b=rgb(h);hh,l,ss=colorsys.rgb_to_hls(r,g,b)
    if ss<.1 or l>.97:hh,ss=210/360,.13
    else:ss=min(ss,smax)*sk*SATS[0]
    return hx(*colorsys.hls_to_rgb(hh,L(l),ss))
SATS=[1]
bgL=lambda l:.165+(1-l)*.42          # white → #24292F-ish, peach/lavender a touch lighter
lineL=lambda l:.30
dropL=lambda l:.075
textL=lambda l:.95-l*.62             # #26323A → light, mid greys → mid-light
SKIP=re.compile(r'\.lf-|#living|\.companion|\.chip-art|svg|\.g-|\.ar-|\.wl-|\.home-room|\.home-walker|\.mg-|\.race|\.karate|\.kt-|\.rc-|\.sky|data-theme|:before|:after|::|^html|^body|^:root|^from|^to$|%')
rules=[]
for m in re.finditer(r'([^{}]+)\{([^{}]*)\}',src):
    sel,body=m.group(1).strip(),m.group(2)
    if sel.startswith('@') or not sel:continue
    rules.append((sel,body))
def sels(sel):return [x.strip() for x in sel.split(',') if x.strip() and not SKIP.search(x.strip())]
def root(x):m=re.search(r'[.#][\w-]+',x);return m.group(0) if m else None
out=[];roots=set()
def decl(body,prop):
    m=re.search(r'(?:^|;)\s*('+prop+r')\s*:\s*([^;]+)',body);return m.group(2).strip() if m else None
# pass 1 — repaint light surfaces
for sel,body in rules:
    S=sels(sel)
    if not S:continue
    new=[]
    for prop in ('background','background-color','background-image'):
        v=decl(body,prop)
        if not v or 'var(' in v:continue
        if re.fullmatch(r'rgba\(255,\s*255,\s*255,\s*\.(8|9)\d*\)(\s*!important)?',v):v=v.replace(re.match(r'rgba\([^)]*\)',v).group(0),'#FFFFFF')
        cols=re.findall(HEX,v)
        if not cols or min(lum(c) for c in cols)<.7:continue
        imp='!important' if '!important' in v else ''
        SATS[0]=.5
        new.append(f'{prop}:'+re.sub(HEX,lambda m:remap(m.group(0),bgL),v.replace('!important','').strip())+imp)
        SATS[0]=1
    if not new:continue
    for prop in ('border','border-color','border-top','border-bottom','outline'):
        v=decl(body,prop)
        if v and re.search(HEX,v):new.append(f'{prop}:'+re.sub(HEX,lambda m:remap(m.group(0),lineL,.4,.5) if lum(m.group(0))>.55 else m.group(0),v))
    v=decl(body,'box-shadow')
    if v and re.search(HEX,v):new.append('box-shadow:'+re.sub(HEX,lambda m:remap(m.group(0),dropL,.4,.6) if lum(m.group(0))>.5 else m.group(0),v))
    c=decl(body,'color')
    if c and re.fullmatch(HEX,c.split('!')[0].strip()) and lum(c[:7])<.6:new.append('color:'+remap(c[:7],textL,.35,.5)+('!important' if '!important' in c else ''))
    elif not c:new.append('color:var(--ink)')
    new.append('--ink:#ECEFF1;--ink-2:#CDD4D9;--muted:#9AA6AE;--line:#3A434C;--line-2:#46505A;--surface-2:#2A3037;--surface-3:#323941')
    for x in S:
        r=root(x)
        if r:roots.add(r)
    out.append(':is('+','.join(S)+'){'+';'.join(new)+'}')
# pass 2 — dark text inside repainted components turns light; light 3-D drops under them darken
for sel,body in rules:
    S=[x for x in sels(sel) if root(x) in roots]
    if not S:continue
    new=[]
    bgv=decl(body,'background') or decl(body,'background-color') or ''
    accent=re.findall(HEX,bgv) and min(lum(c) for c in re.findall(HEX,bgv))<.7   # own accent fill: leave its text alone
    c=decl(body,'color')
    if c and not accent:
        h=re.match(HEX,c)
        if h and lum(h.group(0))<.6:new.append('color:'+remap(h.group(0),textL,.35,.5)+('!important' if '!important' in c else ''))
    v=decl(body,'box-shadow')
    if v and not bgv and re.search(HEX,v) and any(lum(x)>.5 for x in re.findall(HEX,v)):new.append('box-shadow:'+re.sub(HEX,lambda m:remap(m.group(0),dropL,.4,.6) if lum(m.group(0))>.5 else m.group(0),v))
    if new:out.append(':is('+','.join(S)+'){'+';'.join(new)+'}')
D='html[data-theme="dark"] '
open(P,'w').write(s+A+'\n'+'\n'.join(D+o for o in out)+'\n'+B+'\n')
print(len(out),'rules,',len(roots),'components')
