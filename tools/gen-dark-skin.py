#!/usr/bin/env python3
"""V202: components painted with hard-coded light backgrounds keep dark text in the dark theme.
Scans styles.css for rules whose background is made only of light colours and rewrites the generated
block between the DARK-SKIN markers: inside those components the ink variables turn dark."""
import re,sys
P='client/src/styles.css';s=open(P).read()
A='/* DARK-SKIN:start (generated by tools/gen-dark-skin.py) */';B='/* DARK-SKIN:end */'
if A in s:s=s[:s.index(A)].rstrip()+'\n'
src=re.sub(r'/\*.*?\*/','',s,flags=re.S)
def lum(h):
    h=h.lstrip('#');h=''.join(c*2 for c in h[:3]) if len(h) in (3,4) else h[:6]
    r,g,b=[int(h[i:i+2],16)/255 for i in (0,2,4)];return .2126*r+.7152*g+.0722*b
sels=[];keep=[]
i=0;depth=0
for m in re.finditer(r'([^{}]+)\{([^{}]*)\}',src):
    sel,body=m.group(1).strip(),m.group(2)
    if sel.startswith('@')or re.match(r'^(from|to|[\d.,%\s]+)$',sel):continue
    bg=re.search(r'(?:^|;)\s*background(?:-color|-image)?\s*:\s*([^;]+)',body)
    if not bg or 'var(' in bg.group(1) or 'rgba' in bg.group(1):continue
    cols=re.findall(r'#[0-9a-fA-F]{3,8}\b',bg.group(1))
    if not cols or min(lum(c) for c in cols)<0.74:continue
    hascolor=bool(re.search(r'(?:^|;)\s*color\s*:',body))
    for one in sel.split(','):
        one=one.strip()
        if not one or '::' in one or 'data-theme' in one or one.startswith(('html','body','from','to')) or re.search(r':(before|after)',one):continue
        (keep if hascolor else sels).append(one)
uniq=lambda L:list(dict.fromkeys(L))
sels=uniq(sels);keep=[k for k in uniq(keep) if k not in sels]
V='--ink:#26323A;--ink-2:#44545C;--muted:#66747C;--line:#D9CBB0;--line-2:#C9B998;--surface-2:#F3ECDD;--surface-3:#E9DFCB'
out=[A]
def chunks(L,n=40):
    for k in range(0,len(L),n):yield L[k:k+n]
for c in chunks(sels):out.append('html[data-theme="dark"] :is('+','.join(c)+'){'+V+';color:#26323A}')
for c in chunks(keep):out.append('html[data-theme="dark"] :is('+','.join(c)+'){'+V+'}')
out.append(B)
open(P,'w').write(s+'\n'.join(out)+'\n');print(len(sels),len(keep))
