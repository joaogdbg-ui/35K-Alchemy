import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {DATA} from '../client/src/legacy-data.js';
import {PACK} from '../client/src/creative-pack.js';
import {buildCatalog,normalizeCatalogName} from '../client/src/catalog-integrity.js';
import {ORGANIC_V71} from '../client/src/organic-pack-v71.js';
import {ORGANIC_V72} from '../client/src/organic-pack-v72.js';
import {ORGANIC_V73} from '../client/src/organic-pack-v73.js';
import {ORGANIC_ART_V73} from '../client/src/organic-art-v73.js';
const check=(condition,msg)=>{if(!condition)throw Error('V73: '+msg)};
const manifest=JSON.parse(readFileSync('shared/v73-approved.json','utf8'));
check(manifest.version===73&&manifest.cohort_count===24&&manifest.new_items.length===24,'manifest contents');
check(ORGANIC_V73.items.length===24&&ORGANIC_V73.recipes.length===24,'new element and formula counts');
const modes=['gaming-v22','gaming-v23','gaming-v24','gaming-v26','gaming-v27','gaming-v30','organic-v32','organic-v34','organic-v37','organic-v38','organic-v40','organic-v41','organic-v42','organic-v43','organic-v44','organic-v45','organic-v46','organic-v47','organic-v50','organic-v52','organic-v53','organic-v55','organic-v56','organic-v57','organic-v58','organic-v59','organic-v61','organic-v62','organic-v63','organic-v65','organic-v66','organic-v67','organic-v68'];
const packs=[PACK];
for(const n of modes){const f=n.replace('gaming','gaming-pack').replace('organic','organic-pack');const v=await import('../client/src/'+f+'.js');packs.push(Object.values(v)[0]);}
const prior=buildCatalog(DATA,[...packs,ORGANIC_V71,ORGANIC_V72]);
const now=buildCatalog(DATA,[...packs,ORGANIC_V71,ORGANIC_V72,ORGANIC_V73]);
check(prior.items.length===5232&&prior.recipes.size===13569,'V72 baseline changed');
check(now.items.length===5256&&now.recipes.size===13593,'V73 catalog totals incorrect');
for(const [key,value] of prior.recipes)check(now.recipes.get(key)===value,'prior fixed outcome changed '+key);
const priorNames=new Set(prior.items.map(item=>normalizeCatalogName(item.name)));
const artKeys=Object.keys(ORGANIC_ART_V73);
check(artKeys.length===24,'missing or extra drawings');
const seenIds=new Set(),seenHashes=new Set(),seenPairs=new Set();
for(const item of ORGANIC_V73.items){
 check(!priorNames.has(normalizeCatalogName(item.name)),'duplicate existing concept '+item.name);
 check(!/\b(?:legacy|organic\d+):[\w-]+\b/.test(item.summary),'developer IDs leaked in discovery description '+item.name);
 check(!seenIds.has(item.id),'duplicate new ID '+item.id);
 seenIds.add(item.id);
 const approved=manifest.new_items.find(x=>x.id===item.id);
 check(approved?.name===item.name&&approved.art_mode==='bespoke-subject','missing subject approval '+item.name);
 const draw=readFileSync(approved.path,'utf8');
 const hash=createHash('sha256').update(draw).digest('hex');
 check(!seenHashes.has(hash),'duplicate SVG '+item.name);seenHashes.add(hash);
 check(draw===ORGANIC_ART_V73[item.name.toLowerCase()],'source/runtime art mismatch '+item.name);
 check(draw.startsWith('<svg')&&draw.includes('viewBox="0 0 100 100"')&&draw.length>380,'invalid sparse art '+item.name);
 check(!/<script|<image\b|<text\b|<foreignObject|onload\s*=|href\s*=|<animate/i.test(draw),'unsafe SVG '+item.name);
 const recipe=ORGANIC_V73.recipes.find(r=>r[2]===item.id);
 check(recipe&&recipe[0]===approved.ingredients[0]&&recipe[1]===approved.ingredients[1],'recipe/manifest mismatch '+item.name);
 check(prior.items.some(i=>i.id===recipe[0])&&prior.items.some(i=>i.id===recipe[1]),'unknown ingredient '+item.name);
 const key=[recipe[0],recipe[1]].sort().join('|');
 check(!prior.recipes.has(key)&&!seenPairs.has(key),'pair collision '+item.name);seenPairs.add(key);
 check(now.recipes.get(key)===item.id,'non-deterministic formula '+item.name);
}
const app=readFileSync('client/src/app.js','utf8');
check(app.includes('ORGANIC_V71,ORGANIC_V72,ORGANIC_V73,ORGANIC_V74,ORGANIC_V75]'),'V73 catalog import missing');
check(app.includes('ORGANIC_ART_V76[itemName]||ORGANIC_ART_V75[itemName]||ORGANIC_ART_V74[itemName]||ORGANIC_ART_V73[itemName]||ORGANIC_ART_V72[itemName]'),'V73 icon precedence missing');
check(app.includes('const anchorId=this.ids[previousIndex]'),'scroll anchor regression');
const css=readFileSync('client/src/styles.css','utf8');
check(css.includes('.craft-row{transform:translateY(9px)}'),'ingredient row not moved');
check(css.includes('.workspace-content{transform:none}'),'previous whole-workspace translation active');
const builder=readFileSync('tools/build-standalone.py','utf8');
check(builder.includes('window.__gameverseOrganic73')&&builder.includes('35K_Alchemy_V76_Offline.html'),'V73 offline bundle missing');
if(!process.argv.includes('--quiet'))console.log('V73 PASS: 24 bespoke drawings, 5256 elements, 13593 deterministic recipes, unchanged predecessors, targeted layout.');
