#!/usr/bin/env node
/** V85: assemble the Families Only campaign data (owner request 30/10/2026).
 * Sources: tools/v85-family-proposals/<family>-{lead,c1,c2,fix}.json and world-plan.json,
 * written to the brief in tools/v85-family-proposals/BRIEF.md and checked against the catalog.
 * Output: client/src/family-data-v85.js {families:{id:{starters,addMembers}}, recipes:[[a,b,out]]}.
 * Recipes are global (they also become alternative Classic recipes); a pair is kept once,
 * first proposal wins, and the runtime never overwrites an existing catalog pair. */
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..'),dir=resolve(root,'tools/v85-family-proposals');
const ORDER=['nature','music','cinema','consoles','people','fantasy','arcades','anime','games','world'];
const pk=(a,b)=>[a,b].sort().join('|');
const families={},recipes=[],seen=new Map();let dropped=0;
for(const f of ORDER){
 const files=f==='world'?['world-plan']:['lead','c1','c2','fix'].map(s=>f+'-'+s);
 const ps=files.filter(n=>existsSync(resolve(dir,n+'.json'))).map(n=>JSON.parse(readFileSync(resolve(dir,n+'.json'),'utf8')));
 const starters=ps.find(p=>Array.isArray(p.starters))?.starters;
 if(!starters||starters.length!==4)throw Error('V85 family needs 4 starters: '+f);
 const addMembers=[...new Set(ps.flatMap(p=>p.addMembers||[]))].sort();
 families[f]={starters,addMembers};
 for(const p of ps)for(const r of p.recipes||[]){
  const [a,b,o]=r,k=pk(a,b);
  if(seen.has(k)){if(seen.get(k)!==o)dropped++;continue;}
  seen.set(k,o);recipes.push([a,b,o]);
 }
}
writeFileSync(resolve(root,'client/src/family-data-v85.js'),
 '/* V85 Families Only data, generated by tools/v85-assemble-families.mjs. Do not edit by hand. */\n'+
 'export const FAMILY_DATA_V85 = '+JSON.stringify({version:85,families,recipes})+';\n');
console.log(`V85 family data: ${Object.keys(families).length} families, ${recipes.length} recipes (${dropped} superseded duplicates skipped)`);
